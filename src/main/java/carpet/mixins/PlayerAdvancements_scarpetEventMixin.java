package carpet.mixins;

import net.minecraft.advancements.AdvancementHolder;
import net.minecraft.server.PlayerAdvancements;
import net.minecraft.server.level.ServerPlayer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

import static carpet.script.CarpetEventServer.Event.ADVANCEMENT;

@Mixin(PlayerAdvancements.class)
public abstract class PlayerAdvancements_scarpetEventMixin {
    @Shadow private ServerPlayer player;

    @Inject(method = "award", at = @At(value = "INVOKE", target = "Lnet/minecraft/advancements/AdvancementRewards;grant(Lnet/minecraft/server/level/ServerPlayer;)V"))
    private void award(final AdvancementHolder holder, final String criterion, CallbackInfoReturnable<Boolean> cir) {
        ADVANCEMENT.onPlayerAdvancement((ServerPlayer) (Object)player, holder.id());
    }
}
